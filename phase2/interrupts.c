#include "./headers/interrupts.h"
/*
Function that handles Processor Local Timer (PLT) Interrupts
Parameters: processor state at the moment of the interrupt
 */
void local_timer_interrupt_handler(state_t *previous_state)
{
    // Acknowledge the PLT interrupt by loading the timer with a new value using setTIMER.
    setTIMER(TIMESLICE * *(cpu_t *)(TIMESCALEADDR));
    ACQUIRE_LOCK(GLOBAL_LOCK);
    /*Copy the processor state of the current CPU at the time of the
    exception into the Current Process’s PCB (p_s) of the current CPU.*/
    CURRENT_PROC[getPRID()]->p_s = *previous_state;
    // Place the Current Process on the Ready Queue
    insertProcQ(&READY_Q, CURRENT_PROC[getPRID()]);
    CURRENT_PROC[getPRID()] = NULL;
    RELEASE_LOCK(GLOBAL_LOCK);
    // call the scheduler
    scheduler();
}

/*
Function that handles the System-wide Interval Timer and the Pseudo-clock
Parameters: processor state at the moment of the interrupt
 */
void pseudoclock_interrupt_handler(state_t *previous_state)
{
    // Acknowledge the interrupt by loading the Interval Timer with a new value: 100 ms
    LDIT(PSECOND * *(cpu_t *)(TIMESCALEADDR));
    ACQUIRE_LOCK(GLOBAL_LOCK);
    // Unblock all PCBs blocked waiting a Pseudo-clock tick.
    while (headBlocked((int *)&DEVICE_SEMAPHORES[SEMDEVLEN - 1]) != NULL)
    {
        pcb_t *released = removeBlocked((int *)&DEVICE_SEMAPHORES[SEMDEVLEN - 1]);
        insertProcQ(&READY_Q, released);
        DEVICE_SEMAPHORES[SEMDEVLEN - 1] -= 1;
    }
    RELEASE_LOCK(GLOBAL_LOCK);
    // Return control to the Current Process of the current CPU if exists
    if (CURRENT_PROC[getPRID()] != NULL)
        LDST(previous_state);
    else
        scheduler();
}

/*
Function to calculate the Interrupt Line Number based
on the cause value. Note that the if branches are
ordered according to the priority of the interrupts
 */
int getIntLineNo(int cause)
{
    if (cause == 7)
        return 1; // Process Local Timer
    else if (cause == 3)
        return 2; // Interval Timer
    else if (cause == 17)
        return 3; // Disk Devices
    else if (cause == 18)
        return 4; // Flash Devices
    else if (cause == 19)
        return 5; // Network (Ethernet) Devices
    else if (cause == 20)
        return 6; // Printer Devices
    else if (cause == 21)
        return 7; // Terminal Devices
    else
        PANIC();

    return -1; // Unreachable, Used to tell the compiler explicitly that PANIC() does not return
}

/*
Function that handles the Non-Timer Interrupts
Parameters:
- processor state at the moment of the interrupt
- the cause number
 */
void device_interrupt_handler(state_t *previous_state, int cause)
{
    ACQUIRE_LOCK(GLOBAL_LOCK);
    /* Calculate Interrupt Line Number*/
    int IntLineNo = getIntLineNo(cause);
    int devNo;
    /* Beginning address of Interrupting Devices Bit Map*/
    int *linePendingInterrupts = (int *)0x10000040;
    /* Calculate the Device Number: to calculate the device number one can use a series of ifs
    with bitwise AND (&) between the bitmap and the DEVxON constants as conditions.*/
    if (linePendingInterrupts[IntLineNo - 3] & DEV0ON)
        devNo = 0;
    else if (linePendingInterrupts[IntLineNo - 3] & DEV1ON)
        devNo = 1;
    else if (linePendingInterrupts[IntLineNo - 3] & DEV2ON)
        devNo = 2;
    else if (linePendingInterrupts[IntLineNo - 3] & DEV3ON)
        devNo = 3;
    else if (linePendingInterrupts[IntLineNo - 3] & DEV4ON)
        devNo = 4;
    else if (linePendingInterrupts[IntLineNo - 3] & DEV5ON)
        devNo = 5;
    else if (linePendingInterrupts[IntLineNo - 3] & DEV6ON)
        devNo = 6;
    else if (linePendingInterrupts[IntLineNo - 3] & DEV7ON)
        devNo = 7;
    // Calculate the address for this device’s device register by using the Interrupt Line Number and Device Number
    unsigned int *devAddrBase = (memaddr *)(0x10000054 + ((IntLineNo - 3) * 0x80)) + (devNo * 0x10);

    // Check whether the device is a terminal one - made of two sub devices
    if (IntLineNo == 7)
    {
        // Check which of the two sub devices generated the interrupt
        if ((((termreg_t *)devAddrBase)->transm_status & 0xff) == RECVD) // Interrupt generated bye the receiver
            devAddrBase = (unsigned int *)((memaddr)devAddrBase + 0x8);  // Move the pointer to the TRANSM_STATUS address
    }
    int status_code = *devAddrBase;

    unsigned int *commandValue = (unsigned int *)((memaddr)devAddrBase + 0x4); // Save off a pointer to the correct command value address
    *commandValue = ACK;
    // Calculate the correct semaphore index
    int semIndex = getSemaphoreDeviceIndex((memaddr *)commandValue);

    (DEVICE_SEMAPHORES[semIndex])--;
    // Check if there is a process blocked on the device semaphore
    if (headBlocked((int *)&DEVICE_SEMAPHORES[semIndex]) != NULL)
    {
        pcb_t *released = removeBlocked((int *)&DEVICE_SEMAPHORES[semIndex]);
        released->p_s.reg_a0 = status_code;
        insertProcQ(&READY_Q, released);
    }
    // Check if there are no running processes
    if (CURRENT_PROC[getPRID()] == NULL)
    {
        RELEASE_LOCK(GLOBAL_LOCK);
        scheduler();
    }
    else // ...if there are running processes load the correct state
    {
        RELEASE_LOCK(GLOBAL_LOCK);
        /* atomically load the processor state with the state
        located at the supplied address.*/
        LDST(GET_EXCEPTION_STATE_PTR(getPRID()));
    }
}

/*Figure out the current interrupt exception code and The interrupt exception handler’s
first step is to determine which device or timer with an out-standing interrupt is
the highest priority. Depending on the interrupt line and device, the interrupt exception
handler will perform a number of tasks.

The function INTERRUPT_HANDLER receives two parameters, that are
respectively the state at the moment of the exception and the exception code
- in this case it will be an interrupt */
void INTERRUPT_HANDLER(state_t *previous_state, unsigned int exception_code)
{
    int cause = exception_code & CAUSE_EXCCODE_MASK;

    switch (cause)
    {
    case IL_CPUTIMER:
        // Function that handles Processor Local Timer (PLT) Interrupts
        local_timer_interrupt_handler(previous_state);
        break;

    case IL_TIMER:
        // Function that handles the System-wide Interval Timer and the Pseudo-clock
        pseudoclock_interrupt_handler(previous_state);
        break;
    case IL_DISK:
    case IL_FLASH:
    case IL_ETHERNET:
    case IL_PRINTER:
    case IL_TERMINAL:
        // Function that handles Non-Timer Interrupts
        device_interrupt_handler(previous_state, cause);
        break;

    default:
        PANIC();
        break;
    }
}